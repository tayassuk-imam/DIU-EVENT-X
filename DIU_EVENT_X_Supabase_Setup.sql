-- Reference data is readable by website visitors.
drop policy if exists "departments read" on public.departments;
create policy "departments read" on public.departments for select to anon, authenticated using (true);
drop policy if exists "categories read" on public.event_categories;
create policy "categories read" on public.event_categories for select to anon, authenticated using (true);

-- Profiles: users can read their own profile; staff can read all profiles.
drop policy if exists "profiles read own or staff" on public.profiles;
create policy "profiles read own or staff" on public.profiles
for select to authenticated
using (id = (select auth.uid()) or public.is_staff());

drop policy if exists "profiles update own" on public.profiles;
create policy "profiles update own" on public.profiles
for update to authenticated
using (id = (select auth.uid()))
with check (id = (select auth.uid()) and role = 'student');

-- Student profile and preferences: each student controls only their own record.
drop policy if exists "student profile read own or staff" on public.student_profiles;
create policy "student profile read own or staff" on public.student_profiles
for select to authenticated using (user_id = (select auth.uid()) or public.is_staff());
drop policy if exists "student profile insert own" on public.student_profiles;
create policy "student profile insert own" on public.student_profiles
for insert to authenticated with check (user_id = (select auth.uid()));
drop policy if exists "student profile update own" on public.student_profiles;
create policy "student profile update own" on public.student_profiles
for update to authenticated using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));

drop policy if exists "preferences read own or staff" on public.student_preferences;
create policy "preferences read own or staff" on public.student_preferences
for select to authenticated using (user_id = (select auth.uid()) or public.is_staff());
drop policy if exists "preferences insert own" on public.student_preferences;
create policy "preferences insert own" on public.student_preferences
for insert to authenticated with check (user_id = (select auth.uid()));
drop policy if exists "preferences update own" on public.student_preferences;
create policy "preferences update own" on public.student_preferences
for update to authenticated using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));

-- Events: everyone can see published events; staff can see/manage all.
drop policy if exists "published events read" on public.events;
create policy "published events read" on public.events
for select to anon, authenticated using (status = 'published' or public.is_staff());
drop policy if exists "staff insert events" on public.events;
create policy "staff insert events" on public.events
for insert to authenticated with check (public.is_staff());
drop policy if exists "staff update events" on public.events;
create policy "staff update events" on public.events
for update to authenticated using (public.is_staff()) with check (public.is_staff());
drop policy if exists "staff delete events" on public.events;
create policy "staff delete events" on public.events
for delete to authenticated using (public.is_staff());

-- Registrations: students can create/read their own; staff can review/manage all.
drop policy if exists "registrations read own or staff" on public.event_registrations;
create policy "registrations read own or staff" on public.event_registrations
for select to authenticated using (user_id = (select auth.uid()) or public.is_staff());
drop policy if exists "students register themselves" on public.event_registrations;
create policy "students register themselves" on public.event_registrations
for insert to authenticated with check (
  user_id = (select auth.uid())
  and public.current_user_role() = 'student'
  and status = 'pending'
  and exists (select 1 from public.events e where e.id = event_id and e.status = 'published')
);
drop policy if exists "staff review registrations" on public.event_registrations;
create policy "staff review registrations" on public.event_registrations
for update to authenticated using (public.is_staff()) with check (public.is_staff());
drop policy if exists "staff delete registrations" on public.event_registrations;
create policy "staff delete registrations" on public.event_registrations
for delete to authenticated using (public.is_staff());

