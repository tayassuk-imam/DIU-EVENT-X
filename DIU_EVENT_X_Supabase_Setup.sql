-- ---------- Accounts ----------
-- id is the same UUID as auth.users.id. Passwords remain in Supabase Auth.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  role text not null default 'student'
    check (role in ('student','admin','manager')),
  account_status text not null default 'active'
    check (account_status in ('active','inactive','suspended')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.student_profiles (
  user_id uuid primary key references public.profiles(id) on delete cascade,
  student_id text not null unique,
  department_id bigint references public.departments(id) on delete set null
);

create table if not exists public.student_preferences (
  user_id uuid primary key references public.profiles(id) on delete cascade,
  interests text not null default '',
  preferred_category_id bigint references public.event_categories(id) on delete set null
);

-- Automatically create a student profile after Supabase Auth signup.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles(id, full_name, role)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'full_name', ''),
    'student'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

-- Helper functions used by Row Level Security policies.
create or replace function public.current_user_role()
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select role from public.profiles
  where id = (select auth.uid())
    and account_status = 'active'
  limit 1;
$$;

create or replace function public.is_staff()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(public.current_user_role() in ('admin','manager'), false);
$$;

create or replace function public.is_manager()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(public.current_user_role() = 'manager', false);
$$;

-- ---------- Events ----------
create table if not exists public.events (
  id bigint generated by default as identity primary key,
  title text not null,
  category_id bigint not null references public.event_categories(id),
  department_id bigint references public.departments(id) on delete set null,
  organizer text not null default '',
  description text not null default '',
  event_date date not null,
  event_time time,
  location text not null default '',
  registration_deadline date,
  registration_link text not null default '',
  event_type text not null default 'diu'
    check (event_type in ('diu','external')),
  status text not null default 'pending'
    check (status in ('pending','published','cancelled','archived')),
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists events_date_idx on public.events(event_date);
create index if not exists events_status_idx on public.events(status);
create index if not exists events_category_idx on public.events(category_id);

-- ---------- Student actions ----------
create table if not exists public.event_registrations (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  event_id bigint not null references public.events(id) on delete cascade,
  status text not null default 'pending'
    check (status in ('pending','approved','rejected','cancelled')),
  created_at timestamptz not null default now(),
  reviewed_by uuid references public.profiles(id) on delete set null,
  reviewed_at timestamptz,
  unique(user_id, event_id)
);

create table if not exists public.volunteer_applications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  event_id bigint not null references public.events(id) on delete cascade,
  status text not null default 'pending'
    check (status in ('pending','approved','rejected','cancelled')),
  created_at timestamptz not null default now(),
  reviewed_by uuid references public.profiles(id) on delete set null,
  reviewed_at timestamptz,
  unique(user_id, event_id)
);

create table if not exists public.saved_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  event_id bigint not null references public.events(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique(user_id, event_id)
);

create table if not exists public.event_submissions (
  id bigint generated by default as identity primary key,
  submitter_id uuid not null references public.profiles(id) on delete cascade,
  event_id bigint references public.events(id) on delete set null,
  title text not null,
  category_id bigint not null references public.event_categories(id),
  department_id bigint references public.departments(id) on delete set null,
  organizer text not null default '',
  description text not null default '',
  event_date date not null,
  event_time time,
  location text not null default '',
  registration_deadline date,
  registration_link text not null default '',
  status text not null default 'pending'
    check (status in ('pending','approved','rejected')),
  reviewed_by uuid references public.profiles(id) on delete set null,
  review_note text not null default '',
  created_at timestamptz not null default now(),
  reviewed_at timestamptz
);

-- ---------- News and notifications ----------
create table if not exists public.news_posts (
  id bigint generated by default as identity primary key,
  title text not null,
  content text not null,
  status text not null default 'draft'
    check (status in ('draft','published')),
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  title text not null,
  message text not null default '',
  is_read boolean not null default false,
  created_at timestamptz not null default now()
);

create index if not exists notifications_user_created_idx
  on public.notifications(user_id, created_at desc);

